package hooks

import (
	"context"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/charmbracelet/soft-serve/pkg/config"
)

// The names of git server-side hooks.
const (
	PreReceiveHook  = "pre-receive"
	UpdateHook      = "update"
	PostReceiveHook = "post-receive"
	PostUpdateHook  = "post-update"
)

// GenerateHooks generates git server-side hooks for a repository. Currently, it supports the following hooks:
// - pre-receive
// - update
// - post-receive
// - post-update
//
// This function should be called by the backend when a repository is created.
// TODO: support context.
func GenerateHooks(_ context.Context, cfg *config.Config, repo string) error {
	hooksPath := filepath.Join(RepoPath(cfg, repo), "hooks")
	if err := os.MkdirAll(hooksPath, os.ModePerm); err != nil {
		return err
	}

	for _, hook := range []string{
		PreReceiveHook,
		UpdateHook,
		PostReceiveHook,
		PostUpdateHook,
	} {
		// Hooks script/directory path
		hp := filepath.Join(hooksPath, hook)

		// Write the hooks primary script
		if err := writeHook(hp, []byte(hookTemplate)); err != nil {
			return err
		}

		// Create ${hook}.d directory.
		hp += ".d"
		if err := os.MkdirAll(hp, os.ModePerm); err != nil {
			return err
		}

		// Write the soft-serve hook inside ${hook}.d directory.
		if err := writeHook(filepath.Join(hp, "soft-serve"), []byte(softServeHook(runtime.GOOS, hook))); err != nil {
			return err
		}
	}

	return nil
}

// softServeHook returns the soft-serve script of hook, the one in
// hooks/<hook>.d, for a server on goos.
//
// For pre-receive and update it runs the server-wide custom hook,
// $SOFT_SERVE_DATA_PATH/hooks/<hook>, when there is one, and does nothing
// else, so a push starts no soft process for them. The custom hook gets the
// arguments and input `soft hook` gave it: for pre-receive the ref lines on
// stdin, for update the three arguments and an empty stdin. Its exit status
// is the script's.
//
// As in `soft hook`, the custom hook runs only when it is executable, except
// on Windows, which has no execute bit and cannot start an extensionless
// script: there a hook file is run with sh, as git for Windows runs its
// hooks.
//
// post-receive and post-update still run `soft hook <hook>`.
func softServeHook(goos, hook string) string {
	var b strings.Builder
	b.WriteString(`#!/bin/sh
# AUTO GENERATED BY SOFT SERVE, DO NOT MODIFY
if [ -z "$SOFT_SERVE_REPO_NAME" ]; then
	echo "Warning: SOFT_SERVE_REPO_NAME not defined. Skipping hooks."
	exit 0
fi
`)
	var args, stdin string
	switch hook {
	case PreReceiveHook:
	case UpdateHook:
		args, stdin = ` "$1" "$2" "$3"`, " </dev/null"
	case PostReceiveHook:
		fmt.Fprintf(&b, "\"${SOFT_SERVE_BIN_PATH}\" hook %s\n", hook)
		return b.String()
	case PostUpdateHook:
		fmt.Fprintf(&b, "\"${SOFT_SERVE_BIN_PATH}\" hook %s \"$@\"\n", hook)
		return b.String()
	}
	b.WriteString(`if [ -z "$SOFT_SERVE_DATA_PATH" ]; then
	echo "SOFT_SERVE_DATA_PATH is not set; hooks must be run by git from a Soft Serve Plus server" >&2
	exit 1
fi
`)
	fmt.Fprintf(&b, "hook=\"$SOFT_SERVE_DATA_PATH/hooks/%s\"\n", hook)
	if goos == "windows" {
		b.WriteString("[ -f \"$hook\" ] || exit 0\n")
		fmt.Fprintf(&b, "exec sh \"$hook\"%s%s\n", args, stdin)
	} else {
		b.WriteString("[ -f \"$hook\" ] && [ -x \"$hook\" ] || exit 0\n")
		fmt.Fprintf(&b, "exec \"$hook\"%s%s\n", args, stdin)
	}
	return b.String()
}

// hookPerm is the mode of a generated hook script. Git skips hooks that are
// not executable.
const hookPerm fs.FileMode = 0o755

// writeHook writes a hook script and makes it executable. os.WriteFile keeps
// the mode of an existing file, so the mode is set explicitly to repair a hook
// that lost its executable bit, e.g. after a restore from a backup.
func writeHook(path string, data []byte) error {
	if err := os.WriteFile(path, data, hookPerm); err != nil {
		return fmt.Errorf("write hook: %w", err)
	}
	if err := os.Chmod(path, hookPerm); err != nil {
		return fmt.Errorf("make hook executable: %w", err)
	}
	return nil
}

const (
	// hookTemplate allows us to run multiple hooks from a directory. It should
	// support every type of git hook, as it proxies both stdin and arguments.
	hookTemplate = `#!/bin/sh
# AUTO GENERATED BY SOFT SERVE, DO NOT MODIFY
data=$(cat)
exitcodes=""
hookname=$(basename "$0")
GIT_DIR=${GIT_DIR:-$(dirname "$0")/..}
for hook in "${GIT_DIR}/hooks/${hookname}.d"/*; do
  # Avoid running non-executable hooks
  test -x "${hook}" && test -f "${hook}" || continue

  # Run the actual hook
  printf '%s\n' "${data}" | "${hook}" "$@"

  # Store the exit code for later use
  exitcodes="${exitcodes} $?"
done

# Exit on the first non-zero exit code.
for i in ${exitcodes}; do
  [ "${i}" -eq 0 ] || exit "${i}"
done
`
)
